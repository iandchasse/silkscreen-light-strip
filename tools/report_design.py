"""Dump the as-built layout to docs/reports/design_summary.md (read-only; safe while KiCad is open)."""
import math
import os
import sys
from collections import defaultdict

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import params as P  # noqa: E402

ROOT = os.path.dirname(HERE)
mm = pcbnew.ToMM


def main():
    b = pcbnew.LoadBoard(os.path.join(ROOT, P.PROJECT + ".kicad_pcb"))
    out = ["# As-built design summary (generated by tools/report_design.py)", "",
           "Coordinates: main-board KiCad frame (mm, front view, y down). The tail is drawn unrolled in +y past the",
           f"fold line y = {P.PANEL['bottom']} (panel bottom glass edge); x is preserved through the fold.", ""]
    bb = b.GetBoardEdgesBoundingBox()
    out.append(f"Board outline bbox: x {mm(bb.GetLeft()):.3f}..{mm(bb.GetRight()):.3f}, "
               f"y {mm(bb.GetTop()):.3f}..{mm(bb.GetBottom()):.3f}")
    ds = b.GetDesignSettings()
    out.append(f"Board thickness {mm(ds.GetBoardThickness()):.4f} mm; copper layers {b.GetCopperLayerCount()}")
    out.append("")
    out.append("## Footprints")
    out.append("| Ref | Value | Footprint | x | y | rot | pads (num: net @ x,y size) |")
    out.append("|---|---|---|---|---|---|---|")
    fps = sorted(b.GetFootprints(), key=lambda f: (f.GetReference()[0], int(''.join(c for c in f.GetReference() if c.isdigit()) or 0)))
    for fp in fps:
        pads = []
        for p in sorted(fp.Pads(), key=lambda p: p.GetNumber()):
            pos, sz = p.GetPosition(), p.GetSize()
            pads.append(f"{p.GetNumber()}: {p.GetNetname() or '-'} @ {mm(pos.x):.3f},{mm(pos.y):.3f} "
                        f"{mm(sz.x):.2f}x{mm(sz.y):.2f}")
        out.append(f"| {fp.GetReference()} | {fp.GetValue()} | {fp.GetFPIDAsString().split(':')[-1]} | "
                   f"{mm(fp.GetPosition().x):.3f} | {mm(fp.GetPosition().y):.3f} | {fp.GetOrientationDegrees():.0f} | "
                   + "<br>".join(pads) + " |")
    out.append("")
    out.append("## Copper by net")
    per = defaultdict(lambda: {"len": defaultdict(float), "widths": set(), "vias": []})
    for t in b.GetTracks():
        n = t.GetNetname()
        if t.GetClass() == "PCB_VIA":
            per[n]["vias"].append((round(mm(t.GetPosition().x), 3), round(mm(t.GetPosition().y), 3)))
        else:
            per[n]["len"][b.GetLayerName(t.GetLayer())] += mm(t.GetLength())
            per[n]["widths"].add(round(mm(t.GetWidth()), 3))
    out.append("| Net | F.Cu mm | B.Cu mm | widths | vias |")
    out.append("|---|---|---|---|---|")
    for n in sorted(per):
        d = per[n]
        out.append(f"| {n} | {d['len'].get('F.Cu', 0):.1f} | {d['len'].get('B.Cu', 0):.1f} | "
                   f"{sorted(d['widths'])} | {d['vias']} |")
    out.append("")
    out.append("## Graphic layers")
    counts = defaultdict(int)
    for d in b.GetDrawings():
        counts[b.GetLayerName(d.GetLayer())] += 1
    for k in sorted(counts):
        out.append(f"- {k}: {counts[k]} items")
    for d in b.GetDrawings():
        ln = b.GetLayerName(d.GetLayer())
        if ln.startswith("Stiffener") or ln.startswith("Adhesive"):
            r = d.GetBoundingBox()
            out.append(f"  - {ln} {d.GetShapeStr() if hasattr(d, 'GetShapeStr') else 'text'} bbox x {mm(r.GetLeft()):.3f}..{mm(r.GetRight()):.3f} "
                       f"y {mm(r.GetTop()):.3f}..{mm(r.GetBottom()):.3f}")
    out.append("")
    out.append("## Rule areas")
    for z in b.Zones():
        if z.GetIsRuleArea():
            r = z.GetBoundingBox()
            ls = ",".join(b.GetLayerName(l) for l in z.GetLayerSet().Seq())
            out.append(f"- '{z.GetZoneName()}' on {ls}: x {mm(r.GetLeft()):.2f}..{mm(r.GetRight()):.2f} "
                       f"y {mm(r.GetTop()):.2f}..{mm(r.GetBottom()):.2f}; no vias={z.GetDoNotAllowVias()} "
                       f"no pads={z.GetDoNotAllowPads()} no tracks={z.GetDoNotAllowTracks()}")
    path = os.path.join(ROOT, "docs", "reports", "design_summary.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(path)


if __name__ == "__main__":
    main()
